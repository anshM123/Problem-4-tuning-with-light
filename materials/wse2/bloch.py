"""Coherent and incoherent excitons in monolayer WSe2 under resonant excitation (90 K).

Excitonic Bloch equations in the second-order Born-Markov limit (Selig et al., 2D Mater. 5,
035017 (2018); Brem et al., Sci. Rep. 8, 8238 (2018); Christiansen et al., PRB 100, 205401
(2019)):

  coherent polarization at Q = 0 of the bright K-K exciton (K and K' valleys lumped, linear pump):
      dp/dt = -(i delta/hbar + (Gamma_ph + Gamma_rad)/2) p + Omega(t)
  incoherent occupations N_s(eps) of the three valley classes KK, KK', Sigma-K, resolved in
  center-of-mass kinetic energy eps = hbar^2 Q^2 / 2M (isotropic parabolic bands, so energy
  resolution is momentum resolution):
      dN/dt = L N + w |p|^2 - gamma_EEA N_tot N

L is the golden-rule exciton-phonon generator of dynamics.build() (DFPT deformation potentials,
detailed balance at the lattice temperature).  Gamma_ph is the total out-scattering rate of the
Q = 0 bright state given by the same L, and w is the column of L for that state: phonon-induced
dephasing of p creates incoherent excitons in exactly the final states (valley, energy) into
which the Q = 0 exciton scatters (polarization-to-population transfer).  Gamma_rad is the
radiative decay of the Q = 0 polarization; it removes coherent excitons without creating
incoherent ones.  Incoherent excitons inside the light cone (E_lc = E_X^2 / 2Mc^2 = 4.5 ueV)
also decay radiatively; this is included on the lowest energy bin with the light-cone fraction
of that bin.

The photoemission signal of the K valleys is |p|^2 + N_KK + N_KK' (coherent excitons appear at
the exciton energy at K, Christiansen et al. 2019); the Sigma signal is N_SK.  Both lie inside
the measured integration window (1 - 2.5 eV above VB1, all 2 K and 6 Sigma valleys).

The pump has the measured Gaussian intensity envelope (241 fs FWHM, Madeo et al. SI section 4)
and photon energy 1.72 eV, detuned by delta = 10 meV from the 1.73 eV A resonance.  Its
amplitude is set so that the absorbed density (= incoherent excitons generated by dephasing)
equals the stated 8e12 cm^-2.
"""
import numpy as np
from scipy import sparse
from scipy.integrate import solve_ivp
from scipy.optimize import least_squares
from dynamics import build, KB, HBAR

# measured delays and readings of Madeo et al. Fig. 3c (refs/experimental_targets.md, A.4)
EXP_T = np.array([-0.5, -0.2, 0.09, 0.4, 0.7, 1.0, 1.3, 1.6, 2.1, 2.6, 3.1, 3.6])
EXP_K = np.array([0.1, 0.4, 7.5, 6.8, 5.1, 4.2, 3.5, 3.2, 2.5, 1.75, 1.65, 1.35])
EXP_S = np.array([0.1, 0.25, 6.55, 9.8, 9.55, 8.95, 7.8, 6.55, 5.25, 4.45, 3.35, 2.75])

BLOCH = dict(
    E_X=1.73,            # eV, A resonance (Madeo et al. Fig. 2c)
    hw_pump=1.72,        # eV, pump photon energy
    tau_rad=0.2e-12,     # s, radiative lifetime of the Q = 0 bright exciton; lower bound from the
                         # 1.6 meV zero-T, zero-density homogeneous linewidth (T2 = 0.4 ps = 2 T1),
                         # Moody et al., Nat. Commun. 6, 8315 (2015)
)


def generator(model):
    """Sparse golden-rule generator L (dN/dt = L N) on the (species, energy-bin) grid."""
    nE = model["nE"]; nsp = len(model["sp"])
    rows, cols, vals = [], [], []
    for (a, b, r, sh) in model["W"]:
        i = np.arange(max(0, -sh), min(nE, nE - sh))
        j = i + sh
        rows += [b * nE + j, a * nE + i]; cols += [a * nE + i, a * nE + i]
        vals += [np.full(len(i), r), np.full(len(i), -r)]
    n = nsp * nE
    return sparse.csr_matrix((np.concatenate(vals), (np.concatenate(rows), np.concatenate(cols))),
                             shape=(n, n))


def polarization(params, bp, Gam_ph, t):
    """|p(t)|^2 for unit drive amplitude; returns |p|^2 on the grid t (s)."""
    sig = params["pulse_fwhm"] / (2 * np.sqrt(2 * np.log(2)))   # intensity sigma
    delta = bp["E_X"] - bp["hw_pump"]
    g = 0.5 * (Gam_ph + 1.0 / bp["tau_rad"])
    om = lambda s: np.exp(-s ** 2 / (4 * sig ** 2))               # field envelope

    def f(s, y):
        p = y[0] + 1j * y[1]
        d = -(1j * delta / HBAR + g) * p + om(s)
        return [d.real, d.imag]
    sol = solve_ivp(f, (t[0], t[-1]), [0.0, 0.0], t_eval=t, rtol=1e-9, atol=1e-30, max_step=2e-15)
    return sol.y[0] ** 2 + sol.y[1] ** 2


def run_bloch(params, bp=BLOCH, tmax=4e-12, nt=901, coherent=True):
    """Resonant excitation with coherent polarization.  coherent=False injects incoherent
    excitons directly into the Q = 0 bright state (the rate-equation limit of dynamics.run)."""
    m = build(params); p = m["p"]; nE = m["nE"]; eg = m["eg"]
    L = generator(m).tolil()
    # radiative decay of incoherent bright excitons in the light cone (lowest bin of KK)
    E_lc = bp["E_X"] ** 2 / (2 * m["M"]["KK"] * 0.51099895e6)
    f_lc = min(1.0, E_lc / (0.5 * p["de"]))      # bin 0 covers kinetic energies 0 .. de/2
    L[0, 0] -= f_lc / bp["tau_rad"]
    L = L.tocsr()
    col = L[:, 0].toarray().ravel()
    Gam_ph = -col[0] - f_lc / bp["tau_rad"]       # phonon out-scattering of the Q = 0 state
    w = col.copy(); w[0] = 0.0                     # final-state distribution of the dephasing
    tf = np.arange(-0.8e-12, tmax + 1e-15, 1e-15)
    if coherent:
        P2 = polarization(p, bp, Gam_ph, tf)
        scale = p["n_exc"] / (Gam_ph * np.trapezoid(P2, tf))
        P2 *= scale
        src = lambda s: w * np.interp(s, tf, P2)
    else:
        sig = p["pulse_fwhm"] / (2 * np.sqrt(2 * np.log(2)))
        e0 = np.zeros(L.shape[0]); e0[0] = 1.0
        P2 = np.zeros_like(tf)
        src = lambda s: e0 * p["n_exc"] * np.exp(-0.5 * (s / sig) ** 2) / (np.sqrt(2 * np.pi) * sig)
    g = p["g_EEA"]

    def rhs(s, y):
        return L @ y - g * y.sum() * y + src(s)

    t_eval = np.linspace(-0.5e-12, tmax, nt)
    sol = solve_ivp(rhs, (-0.8e-12, tmax), np.zeros(L.shape[0]), t_eval=t_eval, method="LSODA",
                    rtol=1e-7, atol=1e2, max_step=5e-15)
    N = sol.y.reshape(3, nE, -1)
    tot = N.sum(1)
    P2t = np.interp(sol.t, tf, P2)
    return dict(t=sol.t, P2=P2t, KK=tot[0], KKp=tot[1], SK=tot[2], K=P2t + tot[0] + tot[1], S=tot[2],
                N=N, model=m, L=L, Gam_ph=Gam_ph, w=w, f_lc=f_lc,
                n_rad_coh=np.trapezoid(P2, tf) / bp["tau_rad"])


# ---------------------------------------------------------------- measurement operator

def probe_convolve(t, y, fwhm):
    """Convolution with a Gaussian probe envelope of given FWHM (s); fwhm = 0 returns y."""
    if fwhm <= 0:
        return y
    s = fwhm / (2 * np.sqrt(2 * np.log(2)))
    tt = np.linspace(t[0], t[-1], 4 * len(t))
    yy = np.interp(tt, t, y)
    k = np.exp(-0.5 * ((tt - tt.mean()) / s) ** 2); k /= k.sum()
    return np.interp(t, tt, np.convolve(yy, k, mode="same"))


def as_measured(t_ps, K, S, delays=EXP_T):
    """Sample at the measured delays and extract the timing exactly as Madeo et al. do:
    the Sigma maximum among the sampled delays (the '~400 fs', dashed line of Fig. 3d,e) and
    the delay between the sampled maxima of the normalized K and Sigma traces (Fig. S11,
    dotted lines, '~300 fs')."""
    Ks = np.interp(delays, t_ps, K); Ss = np.interp(delays, t_ps, S)
    tK = delays[np.argmax(Ks)]; tS = delays[np.argmax(Ss)]
    return dict(Ks=Ks, Ss=Ss, t_Kmax=tK, t_Smax=tS, delay=tS - tK)


def two_level(tp, A, tau_f, r, tau_d, fwhm=0.241):
    """Effective two-level kinetics (K -> Sigma with time tau_f, back-transfer to the ratio r,
    common decay tau_d), pumped by the Gaussian pulse; returns K(t), Sigma(t) on tp (ps)."""
    sig = fwhm / 2.3548
    tt = np.arange(-1.0, tp.max() + 0.01, 0.002)
    kf = 1 / tau_f; kb = kf * r; kd = 1 / tau_d
    G = A * np.exp(-0.5 * (tt / sig) ** 2) / (np.sqrt(2 * np.pi) * sig)
    Lm = np.array([[-kf - kd, kb], [kf, -kb - kd]])
    lam, V = np.linalg.eig(Lm); Vi = np.linalg.inv(V)
    y = np.zeros((2, len(tt))); dt = tt[1] - tt[0]
    E = V @ np.diag(np.exp(lam * dt)) @ Vi
    Ei = V @ np.diag((np.exp(lam * dt) - 1) / lam) @ Vi
    for i in range(1, len(tt)):
        y[:, i] = E @ y[:, i - 1] + Ei @ np.array([G[i - 1], 0.0])
    return np.interp(tp, tt, y[0]), np.interp(tp, tt, y[1])


def fit_two_level(tp, K, S, sigma=None):
    """Least-squares fit of two_level() to K and Sigma (one common amplitude).  Returns the
    best-fit (A, tau_f, r, tau_d) and the 1-sigma range of tau_f from the profile of chi^2
    (Delta chi^2 = 1, with sigma the reading error)."""
    def res(x, tf_fixed=None):
        A, tf, r, td = x if tf_fixed is None else (x[0], tf_fixed, x[1], x[2])
        k, s = two_level(tp, A, tf, r, td)
        out = np.r_[k - K, s - S]
        return out / (sigma if sigma is not None else 1.0)
    x0 = [np.trapezoid(S, tp) / 2.0, 0.2, 0.5, 2.5]
    b = ([0, 0.003, 0.05, 0.3], [np.inf, 3.0, 5.0, 50.0])
    best = least_squares(res, x0, bounds=b, x_scale=[x0[0], 0.1, 0.1, 1])
    out = dict(A=best.x[0], tau_f=best.x[1], r=best.x[2], tau_d=best.x[3], chi2=2 * best.cost)
    if sigma is not None:
        grid = np.geomspace(0.005, 2.0, 80); prof = []
        for tf in grid:
            rr = least_squares(lambda x: res(x, tf), [best.x[0], best.x[2], best.x[3]],
                               bounds=([0, 0.05, 0.3], [np.inf, 5, 50]))
            prof.append(2 * rr.cost)
        prof = np.array(prof); ok = grid[prof <= prof.min() + 1.0]
        out.update(tau_f_lo=ok.min(), tau_f_hi=ok.max(), profile=(grid, prof))
    return out


def relaxation_modes(params, T=None):
    """Linear relaxation spectrum of the kinetic generator (no annihilation, no source).
    Returns the decay times of the modes and their weights in the bright/dark imbalance
    y = N_K - r_eq N_Sigma after injection at Q = 0 in the K valleys."""
    pp = dict(params)
    if T is not None:
        pp["T"] = T
    m = build(pp); nE = m["nE"]
    L = generator(m).toarray()
    col = L[:, 0].copy(); col[0] = 0.0
    x0 = col / col.sum()                         # state created by dephasing of the Q = 0 polarization
    lam, V = np.linalg.eig(L)
    c = np.linalg.solve(V, x0)
    # equilibrium: eigenvalue closest to 0
    i0 = np.argmin(abs(lam)); neq = np.real(V[:, i0] * c[i0])
    Keq = neq[:2 * nE].sum(); Seq = neq[2 * nE:].sum(); req = Keq / Seq
    proj = np.r_[np.ones(2 * nE), -req * np.ones(nE)]
    amp = np.real(c * (proj @ V))
    amp[i0] = 0.0
    tau = -1 / np.real(lam)
    return dict(tau=tau, amp=amp, r_eq=req, lam=lam)


def rates_table(params, T):
    """Golden-rule rates out of the Q = 0 bright state and thermal valley-transfer rates."""
    pp = dict(params); pp["T"] = T
    m = build(pp); nE = m["nE"]; eg = m["eg"]
    L = generator(m).toarray()
    col = L[:, 0]
    out = dict(G_Q0=-col[0], G_Q0_to_S=col[2 * nE:].sum(), G_Q0_to_KKp=col[nE:2 * nE].sum())
    kT = KB * T
    for s, sl, M in (("K", slice(0, nE), m["M"]["KK"]), ("S", slice(2 * nE, 3 * nE), m["M"]["SK"])):
        f = np.exp(-eg / kT); f /= f.sum()
        x = np.zeros(3 * nE); x[sl] = f
        d = L @ x
        out["thermal_%s_to_S" % s] = d[2 * nE:].sum() if s == "K" else 0.0
        if s == "S":
            out["thermal_S_to_K"] = d[:2 * nE].sum()
    return out
